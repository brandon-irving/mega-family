"""GD seed fixture: a SYNTHETIC fractions worksheet (no real student work), drawn from the six problems on
the design board (design/build/Kids.template.html). Writes the PNG and a TS module carrying it as base64 so
the Convex seed can store it in file storage without any network fetch.

Run from the repo root:  python3 scripts/fixtures/makeHomeworkSheet.py
Needs Pillow and the macOS system fonts (Arial); re-running produces the same image.
"""
import base64
import pathlib

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "shared" / "fixtures" / "homework"
FONT = "/System/Library/Fonts/Supplemental/Arial.ttf"
FONT_BOLD = "/System/Library/Fonts/Supplemental/Arial Bold.ttf"

PROBLEMS = ["1/2 + 1/4 =", "1/2 + 3/8 =", "1/3 + 1/3 =", "2/5 + 1/10 =", "3/4 - 1/4 =", "5/6 - 1/3 ="]


def main() -> None:
    w, h = 900, 1160
    img = Image.new("L", (w, h), 250)
    d = ImageDraw.Draw(img)
    title = ImageFont.truetype(FONT_BOLD, 44)
    body = ImageFont.truetype(FONT, 40)
    small = ImageFont.truetype(FONT, 26)
    d.text((60, 50), "Fractions - Sheet 4", font=title, fill=20)
    d.text((60, 115), "Name: ____________    Grade 5    Add and take away fractions.", font=small, fill=60)
    d.line((60, 160, w - 60, 160), fill=120, width=2)
    y = 210
    for i, p in enumerate(PROBLEMS, start=1):
        d.text((70, y), f"{i}.  {p}", font=body, fill=25)
        d.line((470, y + 44, 700, y + 44), fill=140, width=2)
        y += 150
    d.text((60, h - 70), "Show your work on the back.", font=small, fill=80)
    img = img.convert("P", palette=Image.ADAPTIVE, colors=16)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    png = OUT_DIR / "fractions-sheet-4.png"
    img.save(png, optimize=True)
    b64 = base64.b64encode(png.read_bytes()).decode()
    (OUT_DIR / "fractionsSheet.ts").write_text(
        "// GENERATED by scripts/fixtures/makeHomeworkSheet.py — do not edit by hand.\n"
        "// A synthetic fractions worksheet (no real student work) for the GD seed's homework sheet.\n"
        "export const FRACTIONS_SHEET = {\n"
        "  contentType: 'image/png',\n"
        "  topic: 'Fractions \\u00b7 Sheet 4',\n"
        "  summary: 'Adding and taking away fractions, 6 problems.',\n"
        f"  base64: '{b64}',\n"
        "} as const;\n"
    )
    print(f"wrote {png} ({png.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
